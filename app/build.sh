#!/usr/bin/env bash
# Build the DSH Android shell APK without Gradle.
#
# Toolchain used here is arm64-native: Debian's aapt2 (aarch64) plus the
# official Android build-tools' Java tools (d8, apksigner) running on a local
# JDK. zipalign is replaced by tools/assemble.py, which writes the archive
# itself and keeps resources.arsc uncompressed and 4-byte aligned.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")" && pwd)
BUILD="$ROOT/build"
DIST="$ROOT/dist"

SDK=${ANDROID_SDK_ROOT:-${ANDROID_HOME:-/opt/dsh-build/sdk}}
JAVA=${JAVA_HOME:-/opt/dsh-build/jdk}
BT="$SDK/build-tools/34.0.0"
ANDROID_JAR="$SDK/platforms/android-34/android.jar"

# aarch64 aapt2 (Debian package) + its runtime libraries.
AAPT2=${AAPT2:-/opt/dsh-build/aapt/usr/lib/android-sdk/build-tools/debian/aapt2}
AAPT_LIBS=${AAPT_LIBS:-/opt/dsh-build/7z/usr/lib/7zip:/opt/dsh-build/aapt/usr/lib/aarch64-linux-gnu/android:/opt/dsh-build/aapt/usr/lib/aarch64-linux-gnu}

KEYDIR=${DSH_KEYDIR:-/opt/dsh-build/keys}
KEYSTORE="$KEYDIR/dsh-release.p12"
KEYPASS_FILE="$KEYDIR/dsh-release.pass"
SECRET_FILE=${DSH_BRIDGE_SECRET_FILE:-/home/dsh/.local/state/dsh/bridge.secret}
VERSION_CODE=${VERSION_CODE:-9}
VERSION_NAME=${VERSION_NAME:-1.4.4}

for tool in "$AAPT2" "$BT/d8" "$BT/apksigner" "$ANDROID_JAR" "$JAVA/bin/java" "$JAVA/bin/javac" "$JAVA/bin/keytool"; do
  if [ ! -e "$tool" ]; then
    echo "missing toolchain component: $tool" >&2
    exit 1
  fi
done

export JAVA_HOME="$JAVA"
export PATH="$JAVA/bin:$PATH"

rm -rf "$BUILD"
mkdir -p "$BUILD/gen" "$BUILD/gen-src/dev/dsh/pad" "$BUILD/classes" "$BUILD/dex" "$DIST"

echo "== icons =="
# Dterm icon set (PNG mipmaps plus adaptive/monochrome vectors).
python3 "$ROOT/tools/make_dterm_icon.py" >/dev/null

echo "== bridge secret =="
if [ -f "$SECRET_FILE" ]; then
  BRIDGE_SECRET=$(tr -d '\r\n' < "$SECRET_FILE")
else
  echo "warning: $SECRET_FILE missing; the APK will require manual token paste" >&2
  BRIDGE_SECRET=""
fi
BUNDLE_SECRET=$(printf '%s' "$BRIDGE_SECRET" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')
cat > "$BUILD/gen-src/dev/dsh/pad/BuildSecrets.java" <<JAVA
package dev.dsh.pad;

/** Generated by build.sh — do not edit, do not commit. */
final class BuildSecrets {
    static final String BRIDGE_SECRET = "$BUNDLE_SECRET";
    static final String BRIDGE_URL = "http://127.0.0.1:3081/token";

    private BuildSecrets() {}
}
JAVA

echo "== resources =="
LD_LIBRARY_PATH="$AAPT_LIBS" "$AAPT2" compile --dir "$ROOT/res" -o "$BUILD/res.zip"
LD_LIBRARY_PATH="$AAPT_LIBS" "$AAPT2" link \
  -o "$BUILD/base.apk" \
  -I "$ANDROID_JAR" \
  --manifest "$ROOT/AndroidManifest.xml" \
  -R "$BUILD/res.zip" \
  --auto-add-overlay \
  --java "$BUILD/gen" \
  --min-sdk-version 24 \
  --target-sdk-version 34 \
  --version-code "$VERSION_CODE" \
  --version-name "$VERSION_NAME"

echo "== java =="
SOURCES=$(find "$ROOT/java" "$BUILD/gen" "$BUILD/gen-src" -name '*.java' | sort)
"$JAVA/bin/javac" --release 11 -Xlint:-options -classpath "$ANDROID_JAR" -d "$BUILD/classes" $SOURCES

echo "== dex =="
CLASSES=$(find "$BUILD/classes" -name '*.class' | sort)
"$BT/d8" --release --min-api 24 --lib "$ANDROID_JAR" --output "$BUILD/dex" $CLASSES

echo "== package =="
python3 "$ROOT/tools/assemble.py" "$BUILD/base.apk" "$BUILD/dex/classes.dex" "$BUILD/unsigned.apk"

echo "== sign =="
mkdir -p "$KEYDIR"
chmod 700 "$KEYDIR"
if [ ! -f "$KEYSTORE" ]; then
  PASSPHRASE=$(python3 -c 'import secrets; print(secrets.token_urlsafe(24))')
  printf '%s' "$PASSPHRASE" > "$KEYPASS_FILE"
  chmod 600 "$KEYPASS_FILE"
  "$JAVA/bin/keytool" -genkeypair \
    -keystore "$KEYSTORE" -storetype PKCS12 -alias dsh \
    -keyalg RSA -keysize 2048 -validity 10950 \
    -storepass:file "$KEYPASS_FILE" -keypass:file "$KEYPASS_FILE" \
    -dname "CN=DSH Shell, O=Local, C=CN" >/dev/null 2>&1
fi

OUT="$DIST/Dterm-$VERSION_NAME.apk"
# Passphrases travel through the environment so they never show up in argv/ps.
export DSH_KS_PASS=$(cat "$KEYPASS_FILE")
"$BT/apksigner" sign \
  --ks "$KEYSTORE" --ks-key-alias dsh \
  --ks-pass "env:DSH_KS_PASS" --key-pass "env:DSH_KS_PASS" \
  --v1-signing-enabled true --v2-signing-enabled true --v3-signing-enabled true \
  --min-sdk-version 24 \
  --out "$OUT" "$BUILD/unsigned.apk"

echo "== verify =="
"$BT/apksigner" verify --min-sdk-version 24 --print-certs "$OUT" | sed -n '1,8p'
LD_LIBRARY_PATH="$AAPT_LIBS" "$AAPT2" dump badging "$OUT" | sed -n '1,4p'
ls -lh "$OUT"
echo "OK: $OUT"
